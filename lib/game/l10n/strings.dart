/// Oyunun bütün ekran yazıları, 17 dilde.
///
/// Arayüz de, doğrudan tuvale çizen HUD da yazıları buradan alır:
/// `L.newGame`, `L.levelTitle(3)` gibi. Etkin dil [L.language]'dır; profil
/// yüklenince ve oyuncu dil değiştirince ayarlanır.
///
/// Yeni yazı eklemek: [_tables]'taki her dile aynı anahtarla bir satır ekle
/// ve [L]'ye bir getter yaz. Bir dilde anahtar yoksa İngilizcesi gösterilir.
library;

import 'dart:ui' show Locale;

enum AppLanguage {
  tr('Türkçe'),
  en('English'),
  es('Español'),
  pt('Português (Brasil)'),
  fr('Français'),
  de('Deutsch'),
  it('Italiano'),
  ru('Русский'),
  ar('العربية', rtl: true),
  hi('हिन्दी'),
  th('ไทย'),
  id('Bahasa Indonesia'),
  ja('日本語'),
  ko('한국어'),
  zh('简体中文'), // eski kayıtlarla uyum için adı "zh" kaldı
  zhHant('繁體中文');

  const AppLanguage(this.nativeName, {this.rtl = false});

  /// Dilin kendi dilindeki adı (dil seçim listesinde gösterilir).
  final String nativeName;

  /// Sağdan sola yazılan dil mi.
  final bool rtl;

  /// Kayıtlı dil adından (ör. "de", "zhHant") dil; bilinmiyorsa null.
  static AppLanguage? fromName(String? name) =>
      AppLanguage.values.where((l) => l.name == name).firstOrNull;

  /// Cihaz dilinden (ör. "de-AT", "zh-Hant-TW") dil; desteklenmiyorsa null.
  static AppLanguage? fromLocale(Locale locale) => switch (locale.languageCode) {
    'zh' =>
      locale.scriptCode == 'Hant' ||
              (locale.scriptCode == null &&
                  const {'TW', 'HK', 'MO'}.contains(locale.countryCode))
          ? zhHant
          : zh,
    'in' => id, // eski Android'ler Endonezyacayı "in" diye bildirir
    final code => fromName(code),
  };

  /// Cihazın tercih ettiği diller sırayla denenir; hiçbiri desteklenmiyorsa
  /// İngilizce.
  static AppLanguage fromLocales(List<Locale> locales) =>
      locales.map(fromLocale).nonNulls.firstOrNull ?? en;
}

class L {
  L._();

  static AppLanguage language = AppLanguage.en;

  static String _t(String key, [Map<String, Object> args = const {}]) {
    var text = _tables[language]?[key] ?? _tables[AppLanguage.en]![key] ?? key;
    args.forEach((name, value) => text = text.replaceAll('{$name}', '$value'));
    return text;
  }

  // --- Menü -------------------------------------------------------------------
  static String get subtitle => _t('subtitle');
  static String get newGame => _t('newGame');
  static String get levels => _t('levels');
  static String get shop => _t('shop');
  static String get back => _t('back');
  static String get languageLabel => _t('language');
  static String get swipeToPlay => _t('swipeToPlay');
  static String get swipeHint =>
      _t('swipeHint', {'rise': rise, 'crouch': crouch});
  static String get options => _t('options');
  static String get paused => _t('paused');
  static String get resume => _t('resume');
  static String get mainMenu => _t('mainMenu');
  static String get musicOnLabel => _t('musicOnLabel');
  static String get musicOffLabel => _t('musicOffLabel');
  static String get turnMusicOff => _t('turnMusicOff');
  static String get turnMusicOn => _t('turnMusicOn');

  // --- Bölümler ----------------------------------------------------------------
  static String levelName(int number) => _t('level$number');
  static String? levelTip(int number) =>
      _tables[language]?['tip$number'] ??
      _tables[AppLanguage.en]!['tip$number'];

  /// "3. Bölüm" ve "3. Bölüm · Karlı Vadi".
  static String levelNumber(int number) => _t('levelNumber', {'n': number});
  static String levelWithName(int number) =>
      '${levelNumber(number)} · ${levelName(number)}';

  /// Bölüm başında iki satır: "3. Bölüm" / "Karlı Vadi".
  static String levelTitle(int number) =>
      '${levelNumber(number)}\n${levelName(number)}';

  // --- Sonuç kartları -------------------------------------------------------------
  static String get youLost => _t('youLost');
  static String get playAgain => _t('playAgain');
  static String levelComplete(int number) =>
      _t('levelComplete', {'n': levelNumber(number)});
  static String coinsEarned(int coins) => _t('coinsEarned', {'c': coins});
  static String get nextIsHarder => _t('nextIsHarder');
  static String goToLevel(int number) =>
      _t('goToLevel', {'n': levelNumber(number)});
  static String get congrats => _t('congrats');
  static String get allLevelsDone => _t('allLevelsDone');
  static String get startOver => _t('startOver');

  // --- Mağaza ---------------------------------------------------------------------
  static String shopItemName(String id) => _t('item_$id');
  static String shopItemDescription(String id) => _t('item_${id}_desc');
  static String owned(int count, int max) =>
      _t('owned', {'a': count, 'b': max});
  static String get maxed => _t('maxed');
  static String bought(String item) => _t('bought', {'item': item});
  static String get notEnoughCoins => _t('notEnoughCoins');
  static String limitReached(String item) => _t('limitReached', {'item': item});

  // --- Oyun içi ---------------------------------------------------------------------
  static String get rise => _t('rise');
  static String get crouch => _t('crouch');
  static String get stayStill => _t('stayStill');
  static String get controlsReversedBanner => _t('controlsReversedBanner');
  static String get controlsReversed => _t('controlsReversed');
  static String get controlsNormal => _t('controlsNormal');
  static String leaderBlind(int seconds) => _t('leaderBlind', {'s': seconds});
  static String get tooLate => _t('tooLate');
  static String get shouldStayStill => _t('shouldStayStill');
  static String get wrongMove => _t('wrongMove');
  static String get leaderMissed => _t('leaderMissed');

  /// Kalkan: etkinken altta kalan süre, bir saldırıyı engelleyince uyarı.
  static String shieldActive(int seconds) => _t('shieldActive', {'s': seconds});
  static String get shieldBlocked => _t('shieldBlocked');
  static String get trick => _t('trick');
  static String flippedBy(String name) => _t('flippedBy', {'name': name});
  static String blindedBy(String name) => _t('blindedBy', {'name': name});

  /// Ters kontrolü yapan karakterin laf sokması (1..[tauntCount]).
  static const int tauntCount = 4;
  static String taunt(int index) => _t('taunt$index');

  /// 7. bölümde rakiplerin "dayanamazsın" diye laf sokması (1..[endureTauntCount]).
  static const int endureTauntCount = 5;
  static String endureTaunt(int index) => _t('endure$index');

  /// Çift komut gelince komutun altında çıkan kısa uyarı.
  static String get doubleCommand => _t('doubleCommand');
  static String get minusLife => _t('minusLife');
  static String get outBig => _t('outBig');
  static String get wonBig => _t('wonBig');
  static String get levelDoneBig => _t('levelDoneBig');
  static String isOut(String name) => _t('isOut', {'name': name});
}

